package com.example.g2glasses.glassesui

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/** Mirrors CaptionWrapTests in capstone_tests/tests/test_bridge_unit.py, plus golden cases from wrap(). */
class CaptionLayoutTest {

    private fun utf8(s: String) = s.toByteArray(Charsets.UTF_8)

    @Test
    fun emptyWindow() {
        assertEquals("", CaptionLayout.wrap(emptyList(), 34, 6, 950))
    }

    @Test
    fun newestUtterancesRemain() {
        assertEquals("middle\nnew", CaptionLayout.wrap(listOf("old", "middle", "new"), 20, 2, 950))
    }

    @Test
    fun wordBoundaryWrapping() {
        assertEquals("one two\nthree\nfour", CaptionLayout.wrap(listOf("one two three four"), 7, 6, 950))
    }

    @Test
    fun utf8ByteCeiling() {
        for (line in listOf("日本語テキスト".repeat(80), "hello 🌍".repeat(100), "café ".repeat(200))) {
            val result = CaptionLayout.wrap(listOf(line), 1000, 6, 95)
            val bytes = utf8(result)
            assertTrue("${bytes.size} bytes", bytes.size <= 95)
            // Round-trips only if no code point (or surrogate pair) was split.
            assertEquals(result, String(bytes, Charsets.UTF_8))
        }
    }

    @Test
    fun olderLinesTrimBeforeLatest() {
        val txt = CaptionLayout.wrap(listOf("outdated caption", "new caption"), 80, 6, 15)
        assertTrue(utf8(txt).size <= 15)
        assertEquals("new caption", txt)
    }

    @Test
    fun defaultByteCapIs950() {
        val result = CaptionLayout.wrap(listOf("ã".repeat(2000)), 1000, 6)
        assertTrue(utf8(result).size <= 950)
    }

    /** Expected outputs generated by running g2_bridge.wrap() in Python. */
    @Test
    fun matchesPythonGoldenOutputs() {
        data class Case(val window: List<String>, val cols: Int, val lines: Int, val cap: Int, val out: String)
        val cases = listOf(
            Case(listOf("where is the train station", "how much does this cost"), 12, 6, 950,
                "where is the\ntrain\nstation\nhow much\ndoes this\ncost"),
            Case(listOf("a b c d e f g h i j k l m n o p"), 5, 3, 950, "j k l\nm n o\np"),
            Case(listOf("supercalifragilistic"), 6, 6, 950, "superc\nalifra\ngilist\nic"),
            Case(listOf("ab supercalifragilistic"), 6, 6, 950, "ab sup\nercali\nfragil\nistic"),
            Case(listOf("good morning", "the next train leaves from platform four", "thank you"), 16, 4, 950,
                "the next train\nleaves from\nplatform four\nthank you"),
            Case(listOf("olá   tudo    bem"), 20, 6, 950, "olá   tudo    bem"),
            Case(listOf("first", "second", "third", "fourth"), 34, 6, 20, "second\nthird\nfourth"),
            Case(listOf("você está bem? sim, obrigado"), 10, 6, 950, "você está\nbem? sim,\nobrigado"),
            Case(listOf("one", "", "three"), 10, 6, 950, "one\n\nthree"),
            Case(listOf("x".repeat(50)), 34, 6, 950, "x".repeat(34) + "\n" + "x".repeat(16)),
        )
        for (c in cases) {
            assertEquals(c.window.toString(), c.out, CaptionLayout.wrap(c.window, c.cols, c.lines, c.cap))
        }
    }
}
